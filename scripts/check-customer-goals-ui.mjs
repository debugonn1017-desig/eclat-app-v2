// preview-customer-goals.mjs 専用。本番URLを受け付けず、架空データだけを操作。
import assert from 'node:assert/strict'
import fs from 'node:fs'
import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.ECLAT_PLAYWRIGHT_MODULE || 'playwright')
const origin = 'http://127.0.0.1:6116'
const out = process.env.ECLAT_GOALS_QA_DIR || '/private/tmp/eclat-goals-qa'
fs.mkdirSync(out, { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const errors = []
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, acceptDownloads: true })
  page.on('pageerror', e => errors.push(e.message))
  await page.request.get(origin + '/fixture/reset')
  await page.goto(origin)
  await page.waitForFunction(() => document.querySelectorAll('[data-customer-id]').length === 56)
  await page.getByRole('button', { name: 'PDF保存', exact: true }).waitFor({ state: 'visible' })
  await page.waitForFunction(() => ![...document.querySelectorAll('button')].find(b => b.textContent === 'PDF保存')?.disabled)
  const dimensions = await page.evaluate(() => ({ width: document.documentElement.scrollWidth, first: document.querySelector('[data-customer-id]').getBoundingClientRect().top, height: document.querySelector('[data-customer-id]').getBoundingClientRect().height }))
  assert.equal(dimensions.width, 390); assert.ok(dimensions.first < 330); assert.ok(dimensions.height < 160)
  await page.screenshot({ path: out + '/mobile.png' })

  // 明示編集・競合時の入力保持・ゼロと未設定・月切替後の復元。
  await page.getByRole('button', { name: /^県外顧客/ }).click()
  const row = page.locator('[data-customer-id="3"]')
  await row.getByRole('button', { name: '山本さんの操作を表示' }).click()
  await row.getByRole('button', { name: /目標・備考/ }).click()
  let editor = page.getByRole('dialog', { name: /山本さん · 目標・備考の編集/ })
  await editor.getByRole('spinbutton', { name: '目標売上（円）' }).fill('0')
  await editor.getByRole('spinbutton', { name: '目標来店回数（回）' }).fill('')
  await editor.getByRole('textbox', { name: '月別の備考' }).fill('保存テスト：<script>文字は安全に表示</script>\n2行目の備考')
  await page.request.get(origin + '/fixture/conflict')
  await editor.getByRole('button', { name: '保存する', exact: true }).click()
  await editor.getByRole('alert').waitFor()
  assert.equal(await editor.getByRole('spinbutton', { name: '目標売上（円）' }).inputValue(), '0')
  await page.keyboard.press('Escape')
  await editor.getByRole('button', { name: '編集を続ける' }).click()
  await editor.getByRole('button', { name: '保存する', exact: true }).click()
  await editor.waitFor({ state: 'hidden' })
  assert.match(await row.innerText(), /¥0/); assert.match(await row.innerText(), /未設定/)
  await page.getByLabel('目標の対象月').fill('2026-12')
  await page.waitForFunction(() => document.body.innerText.includes('目標未設定'))
  await page.getByLabel('目標の対象月').fill('2026-11')
  await page.waitForFunction(() => document.body.innerText.includes('保存テスト'))
  await page.reload()
  await page.waitForFunction(() => document.querySelectorAll('[data-customer-id]').length === 56)

  // 確認は行幅・高さ・横位置を保ち、元の連絡状況を維持して記録される。
  const checkRow = page.locator('[data-customer-id="2"]')
  await checkRow.scrollIntoViewIfNeeded()
  const before = await checkRow.boundingBox()
  const beforeScroll = await page.evaluate(() => ({ x: scrollX, y: scrollY }))
  await checkRow.getByRole('button', { name: '本日確認', exact: true }).click()
  await checkRow.getByRole('button', { name: /本日確認済み/ }).waitFor()
  const after = await checkRow.boundingBox(), afterScroll = await page.evaluate(() => ({ x: scrollX, y: scrollY }))
  assert.equal(before.x, after.x); assert.equal(before.width, after.width); assert.equal(before.height, after.height); assert.deepEqual(afterScroll, beforeScroll)
  let state = await (await page.request.get(origin + '/fixture/state')).json()
  assert.equal(state.cycles.find(c => c.customer_id === 2).last_status, '返信待ち')
  assert.equal(state.events.length, 1)
  await checkRow.getByRole('button', { name: '記録・ログ' }).click()
  await page.getByRole('dialog').last().getByText('本日、連絡状況を確認しました。', { exact: true }).waitFor()
  await page.keyboard.press('Escape')

  // 550ms長押し→情報→実際の個人ページとフォーム→保存→元の情報/一覧。
  const target = page.locator('[data-customer-id="20"]')
  await target.scrollIntoViewIfNeeded()
  const scroll = await page.evaluate(() => ({ x: scrollX, y: scrollY }))
  const name = await target.locator('[role="button"]').boundingBox()
  const cdp = await page.context().newCDPSession(page)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: name.x + 35, y: name.y + 10 }] })
  await page.waitForTimeout(650)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  let info = page.getByRole('dialog', { name: 'お客様20のお客様情報' })
  await info.waitFor()
  await info.evaluate(e => { e.scrollTop = 100 })
  const infoTop = await info.evaluate(e => e.scrollTop)
  await info.getByRole('button', { name: '個人ページを開く' }).click()
  const personal = page.getByRole('dialog', { name: 'お客様の個人ページ', exact: true })
  await personal.getByRole('button', { name: '編集', exact: true }).click()
  await personal.locator('input[name="customer_name"]').fill('お客様20・変更済み')
  await personal.locator('select[name="region"]').selectOption('東京都')
  assert.equal(await personal.getByRole('button', { name: 'お客様の個人ページを閉じる' }).isDisabled(), true)
  assert.equal(await personal.locator('input[name="monthly_target_sales"]').count(), 0)
  await personal.getByRole('button', { name: '入力内容を保存する' }).click()
  await personal.getByRole('button', { name: '編集', exact: true }).waitFor()
  await personal.getByRole('button', { name: 'お客様の個人ページを閉じる' }).click()
  await personal.waitFor({ state: 'hidden' })
  info = page.getByRole('dialog').last()
  assert.equal(await info.evaluate(e => e.scrollTop), infoTop)
  await info.getByRole('button', { name: '一覧に戻る' }).click()
  await page.waitForFunction(() => document.querySelector('[data-customer-id="20"]')?.innerText.includes('変更済み'))
  assert.equal(await page.getByLabel('目標の対象月').inputValue(), '2026-11')
  const returned = await page.evaluate(() => ({ x: scrollX, y: scrollY }))
  assert.deepEqual(returned, scroll)
  assert.match(await target.innerText(), /東京都/)

  // スワイプで編集操作が開く。
  await target.scrollIntoViewIfNeeded()
  const box = await target.boundingBox(), y = box.y + 30
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 330, y }] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 180, y }] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await target.getByRole('button', { name: /目標・備考/ }).waitFor()
  await target.getByRole('button', { name: '戻る', exact: true }).click()

  // 星解除で合計から外れ、DBの月別入力は残る。
  await page.getByRole('button', { name: /^全分類/ }).click()
  const remove = page.locator('[data-customer-id="1"]')
  await remove.getByRole('button', { name: '田中さんの操作を表示' }).click()
  page.once('dialog', dialog => dialog.accept())
  await remove.getByRole('button', { name: '⭐️解除', exact: true }).click()
  await remove.waitFor({ state: 'hidden' })
  state = await (await page.request.get(origin + '/fixture/state')).json()
  assert.equal(state.goals.find(g => g.customer_id === 1).target_sales, 300000)
  assert.equal(await page.locator('[data-customer-id]').count(), 55)

  // 表示の絞り込みと独立した全員PDFを直接保存。日本語備考・複数ページ。
  await page.getByRole('button', { name: /^県外顧客/ }).click()
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'PDF保存', exact: true }).click()
  const download = await downloadEvent; await download.saveAs(out + '/customer-goals.pdf')
  assert.ok(fs.statSync(out + '/customer-goals.pdf').size > 10000)
  assert.ok(download.suggestedFilename().endsWith('.pdf'))
  let printRows = 0
  await page.exposeFunction('capturePrintRows', n => { printRows = n })
  await page.emulateMedia({ media: 'print' })
  await page.evaluate(() => { window.print = () => { window.capturePrintRows(document.querySelector('body>article table tbody').rows.length) } })
  await page.getByRole('button', { name: '印刷', exact: true }).click()
  await page.waitForFunction(() => document.body.dataset.customerGoalsPrint === 'true' && document.querySelector('body>article table tbody')?.rows.length === 55)
  await page.pdf({ path: out + '/native-print.pdf', preferCSSPageSize: true, printBackground: true })
  await page.evaluate(() => window.dispatchEvent(new Event('afterprint')))
  await page.emulateMedia({ media: 'screen' })
  await page.waitForFunction(() => !document.body.dataset.customerGoalsPrint)
  assert.equal(printRows, 55)
  assert.equal(await page.locator('body>article').count(), 0)

  // 各画面幅、閲覧専用、エラーをゼロ実績と誤表示しないこと。
  for (const width of [320, 390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 }); await page.goto(origin)
    await page.waitForFunction(() => document.querySelectorAll('[data-customer-id]').length === 55)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), width, `overflow at ${width}`)
    if (width === 1440) await page.screenshot({ path: out + '/desktop.png' })
  }
  await page.goto(origin + '/?readonly=1')
  await page.waitForFunction(() => document.querySelectorAll('[data-customer-id]').length === 55)
  assert.equal(await page.getByRole('button', { name: /の操作を表示/ }).count(), 0)
  assert.equal(await page.getByRole('button', { name: '本日確認', exact: true }).first().isDisabled(), true)
  await page.goto(origin)
  await page.locator('[data-customer-id="2"]').getByRole('button', { name: '佐藤さんの操作を表示' }).click()
  await page.locator('[data-customer-id="2"]').getByRole('button', { name: /目標・備考/ }).click()
  const retainedEditor = page.getByRole('dialog', { name: /佐藤さん · 目標・備考の編集/ })
  await retainedEditor.getByRole('textbox', { name: '月別の備考' }).fill('別の人が星を解除しても残す下書き')
  await page.request.post(origin + '/fixture/remove', { data: ['2'] })
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await page.waitForFunction(() => document.querySelectorAll('[data-customer-id]').length === 54)
  assert.equal(await retainedEditor.getByRole('textbox', { name: '月別の備考' }).inputValue(), '別の人が星を解除しても残す下書き')
  await retainedEditor.getByRole('button', { name: '保存する', exact: true }).click()
  await retainedEditor.getByRole('alert').waitFor()
  assert.match(await retainedEditor.getByRole('alert').innerText(), /⭐️が解除/)
  await page.keyboard.press('Escape')
  await retainedEditor.getByRole('button', { name: '破棄して閉じる' }).click()
  await retainedEditor.waitFor({ state: 'hidden' })
  await page.request.get(origin + '/fixture/fail')
  await page.reload()
  await page.getByRole('alert').waitFor()
  assert.equal(await page.getByRole('button', { name: 'PDF保存', exact: true }).isDisabled(), true)
  assert.match(await page.locator('[data-customer-id]').first().innerText(), /取得を確認中/)
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ ok: true, dimensions, checks: ['56人連続表示', '月別保存・競合・ゼロと未設定', '本日確認の位置と状況維持', '長押し', '実個人ページで編集保存・復帰', 'スワイプ', '⭐️解除後の保持', 'PDF直接保存', '全員印刷と復帰', '5画面幅', '閲覧権限', '他端末の⭐️解除でも下書きを保持', '取得エラー'], output: out }))
} finally { await browser.close() }
