// localhostの実部品＋架空APIのみ。実機Safari・インストール済みPWAの検証とは区別する。
import assert from 'node:assert/strict'
import fs from 'node:fs'
import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.ECLAT_PLAYWRIGHT_MODULE || 'playwright')
const origin = 'http://127.0.0.1:6116'
const out = '/private/tmp/eclat-customer-meetings-mobile-qa'
fs.mkdirSync(out, { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const checks = [], errors = []
const stateOf = async page => (await page.request.get(origin + '/fixture/state')).json()
const withoutMeetings = state => Object.fromEntries(Object.entries(state).filter(([key]) => key !== 'meetingRecords'))
try {
  for (const width of [320, 390, 768, 1440]) {
    const page = await browser.newPage({ viewport: { width, height: 844 }, hasTouch: true })
    page.on('pageerror', error => errors.push(error.message))
    await page.request.get(origin + '/fixture/reset?staff=1')
    await page.request.get(origin + '/fixture/meeting-setup')
    await page.goto(origin + '/?staff=1')
    await page.getByRole('button', { name: /^1\. 本日確認/ }).click()
    await page.getByRole('button', { name: '会議モード', exact: true }).click()
    await page.getByLabel('会議の来店日').fill('2026-11-02')
    const table = page.locator('[data-customer-meeting-table]'), row = table.locator('[data-meeting-visit="301"]')
    const scroll = table.getByLabel('会議表・横スクロール')
    const edit = row.locator('[data-meeting-edit]')
    await edit.waitFor()
    await page.waitForFunction(() => !document.querySelector('[data-meeting-edit="301"]').disabled)
    assert.equal(await table.locator('[data-meeting-visit="101"]').count(), 0)
    assert.equal(await table.locator('[data-meeting-visit="102"]').count(), 1)
    assert.equal(await table.locator('[data-meeting-visit="303"]').count(), 0)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true)
    if (width < 768) {
      const identity = row.locator('td:first-child').getByText('あかり・お客様3', { exact: true })
      assert.equal(await identity.isVisible(), true)
      const bounds = await identity.boundingBox()
      assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width)
    }
    await page.screenshot({ path: out + `/meeting-${width}.png`, fullPage: false })
    await edit.scrollIntoViewIfNeeded()
    await scroll.evaluate(element => { element.scrollLeft = element.scrollWidth })
    assert.ok(await scroll.evaluate(element => element.scrollLeft > 1000))
    const left = await scroll.evaluate(element => element.scrollLeft)
    const before = await stateOf(page)
    await edit.click()
    const editor = page.getByRole('dialog', { name: /あかり・お客様3 ／ 2026\/11\/02/ })
    await editor.getByLabel('次回につながる情報').fill(`${width}pxから会議編集`)
    await editor.getByRole('checkbox', { name: 'リピート', exact: true }).check()
    assert.equal(await page.getByLabel('会議の来店日').isDisabled(), true)
    if (width < 768) {
      await page.setViewportSize({ width, height: 430 })
      const save = editor.getByRole('button', { name: '保存・メモ履歴へ反映', exact: true })
      await save.scrollIntoViewIfNeeded()
      const bounds = await save.boundingBox()
      assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width && bounds.y >= 0 && bounds.y + bounds.height <= 430)
      assert.ok(bounds.height >= 40)
    }
    await editor.getByRole('button', { name: '保存・メモ履歴へ反映', exact: true }).click()
    await editor.waitFor({ state: 'hidden' })
    const after = await stateOf(page)
    assert.deepEqual(withoutMeetings(after), withoutMeetings(before))
    assert.equal(after.meetingRecords.at(-1).values.repeat, true)
    assert.equal(await scroll.evaluate(element => element.scrollLeft), left)
    const repeat = row.getByRole('checkbox', { name: /のリピート$/ })
    await repeat.waitFor()
    await page.waitForFunction(() => document.querySelector('[data-meeting-visit="301"] input[aria-label$="のリピート"]').checked)
    await repeat.uncheck()
    await table.getByRole('status').filter({ hasText: '会議記録を保存' }).waitFor()
    await page.waitForFunction(() => !document.querySelector('[data-meeting-edit="301"]').disabled)
    assert.equal((await stateOf(page)).meetingRecords.at(-1).values.repeat, false)
    if (width < 768) await page.setViewportSize({ width, height: 844 })
    await page.getByRole('button', { name: '通常の一覧', exact: true }).click()
    await page.getByRole('group', { name: '⭐️の表示対象' }).waitFor()
    checks.push(`${width}px：会議入口・名前・表内横スクロール・リピート編集/自動保存・元の位置・通常一覧復帰`)
    await page.close()
  }

  // インストール表示のブラウザ条件を模擬。ネイティブシェルの実機測定ではない。
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true })
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => {
    Object.defineProperty(navigator, 'standalone', { get: () => true })
    const original = window.matchMedia.bind(window)
    window.matchMedia = query => query === '(display-mode: standalone)' ? Object.assign(original(query), { matches: true }) : original(query)
  })
  await page.request.get(origin + '/fixture/reset?staff=1')
  await page.request.get(origin + '/fixture/meeting-setup')
  await page.goto(origin + '/?staff=1')
  await page.getByRole('button', { name: /^1\. 本日確認/ }).click()
  await page.getByRole('group', { name: '⭐️の表示対象' }).getByRole('button', { name: '⭐️全員', exact: true }).click()
  const category = page.locator('details[data-goal-category="県内場内"]')
  await category.locator(':scope>summary').click()
  const ledger = page.locator('[data-customer-ledger][data-customer-id="3"]')
  await ledger.scrollIntoViewIfNeeded()
  const logButton = ledger.getByRole('button', { name: /記録・ログ/ })
  await logButton.evaluate(element => element.scrollIntoView({ block: 'center', inline: 'nearest' }))
  const before = await stateOf(page), position = await page.evaluate(() => ({ x: scrollX, y: scrollY }))
  await logButton.click()
  const log = page.getByRole('dialog', { name: 'あかり・お客様3の⭐️記録', exact: true })
  await log.waitFor()
  await log.locator('[data-customer-meeting-history="3"] > details > summary').click()
  await log.getByRole('button', { name: 'この来店分を一括編集', exact: true }).waitFor()
  await log.getByLabel('会議記録を新しくつける来店').selectOption('302')
  await log.getByRole('button', { name: 'この来店分を一括編集', exact: true }).click()
  const editor = page.getByRole('dialog', { name: /あかり・お客様3 ／ 2026\/11\/02/ })
  await editor.getByLabel('次回につながる情報').fill('通常の記録・ログから新規入力')
  await editor.getByRole('checkbox', { name: 'リピート', exact: true }).check()
  await editor.getByRole('button', { name: '保存・メモ履歴へ反映', exact: true }).click()
  await editor.waitFor({ state: 'hidden' })
  const after = await stateOf(page), record = after.meetingRecords.filter(record => record.visit_id === '302').at(-1)
  assert.equal(record.values.repeat, true)
  assert.deepEqual(withoutMeetings(after), withoutMeetings(before))
  const card = log.locator(`[data-meeting-record-id="${record.id}"]`)
  await card.waitFor()
  assert.match(await card.innerText(), /リピート.*あり/)
  await card.getByRole('button', { name: /一括編集/ }).click()
  await editor.getByRole('checkbox', { name: 'リピート', exact: true }).uncheck()
  await editor.getByRole('button', { name: '保存・メモ履歴へ反映', exact: true }).click()
  await editor.waitFor({ state: 'hidden' })
  assert.equal((await stateOf(page)).meetingRecords.filter(record => record.visit_id === '302').at(-1).values.repeat, false)
  await page.screenshot({ path: out + '/normal-log-standalone.png', fullPage: false })
  await log.getByRole('button', { name: '一覧に戻る', exact: true }).click()
  await log.waitFor({ state: 'hidden' })
  assert.equal(await category.evaluate(element => element.open), true)
  assert.deepEqual(await page.evaluate(() => ({ x: scrollX, y: scrollY })), position)
  checks.push('standalone条件：会議モードに入らず通常ログから未保存来店を入力/既存編集・リピート共有・元の分類/位置へ復帰')
  await page.getByRole('button', { name: '会議モード', exact: true }).click()
  await page.getByLabel('会議の来店日').fill('2026-11-02')
  await page.locator('[data-meeting-visit="302"]').waitFor()
  assert.equal(await page.locator('[data-meeting-visit="302"]').getByRole('checkbox', { name: /のリピート$/ }).isChecked(), false)
  checks.push('同じ保存内容がスマホ会議表に反映される')
  await page.goto(origin + '/?staff=1&readonly=1')
  await page.getByRole('button', { name: /^1\. 本日確認/ }).click()
  await page.getByRole('button', { name: '会議モード', exact: true }).click()
  await page.getByLabel('会議の来店日').fill('2026-11-02')
  await page.locator('[data-meeting-visit="301"]').waitFor()
  assert.equal(await page.locator('[data-meeting-edit="301"]').isDisabled(), true)
  assert.equal(await page.locator('[data-meeting-visit="301"]').getByRole('checkbox', { name: /のリピート$/ }).isDisabled(), true)
  checks.push('スマホでも閲覧専用スタッフは会議編集・リピート更新不可')
  await page.close()
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ passed: checks, errors }, null, 2))
} finally { await browser.close() }
